# Format specs: fixed-point floats past 1e21, zero padding with grouping,
# the '#' alternate form and non-finite values with '%'.
specs = [
    ('1e21', 1e21, '.2f'),
    ('2.5e22', 2.5e22, '.2f'),
    ('6.02e23', 6.02e23, ',.0f'),
    ('2.0**80', 2.0**80, '.1f'),
    ('-1234.5', -1234.5, '012,.2f'),
    ('1234567', 1234567, '012,'),
    ('-5', -5, '+06_d'),
    ('5', 5, '#.0f'),
    ('123.0', 123.0, '#.3g'),
    ('float("inf")', float("inf"), '.0%'),
    ('1e20', 1e20, '#'),
    ('5.0', 5.0, '#'),
    ('5.0', 5.0, '#.3'),
    ('5.0', 5.0, '#.0e'),
    ('255', 255, '#012_x'),
    ('255', 255, '012_b'),
    ('1234.5', 1234.5, '012_.1f'),
    ('-0.0', -0.0, '08,.1f'),
    ('1e22', 1e22, 'f'),
    ('10**20', 10**20, '%'),
    ('1234', 1234, '0=12,'),
    ('12345.678', 12345.678, '015,.2f'),
    ('1.5', 1.5, '#g'),
    ('1e-5', 1e-5, '#.2g'),
    ('float("nan")', float("nan"), '#.1f'),
    ('float("-inf")', float("-inf"), '010.1f'),
    ('123456789', 123456789, '020,d'),
    ('1e300', 1e300, '.1f'),
    ('1234.5', 1234.5, '10,.1f'),
    ('-1234567', -1234567, ',d'),
    ('1234567', 1234567, '_d'),
    ('255', 255, '_x'),
    ('65535', 65535, '#_b'),
    ('5', 5, '05d'),
    ('-5', -5, '05d'),
    ('3.14159', 3.14159, '08.3f'),
    ('-3.14159', -3.14159, '+09.2f'),
    ('1234', 1234, '*^12,'),
    ('0', 0, '05,'),
    ('12', 12, '#o'),
    ('0.5', 0.5, '.0%'),
    ('1234.5', 1234.5, ',.2%'),
    ('7', 7, '#x'),
    ('1e16', 1e16, ',.0f'),
    ('-1e21', -1e21, '.1f'),
]
for name, v, s in specs:
    try:
        print(name, repr(s), repr(format(v, s)))
    except Exception as e:
        print(name, repr(s), type(e).__name__, e)
print('%.2f' % 2.5e22, '%.2f' % 1e21, '%d' % 5, '%#.0f' % 5.0, '%010.2f' % -1234.5, '%.0f' % 1e25)
print(f'{1e21:.2f}', f'{-1234.5:012,.2f}', f'{1234567:012,}', f'{5:#.0f}', f'{123.0:#.3g}', format(float('inf'), '.0%'))
print(round(1e22, 2), round(2.5e21, 1))
