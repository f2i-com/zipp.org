"""Generate the default (locale-independent) case-mapping tables in
crates/zipp-vm/src/vm/special_casing.rs.

    python tools/gen_case_tables.py [--toolchain +1.92.0]

The mappings are the standard library's own: a small Rust program built with
the pinned toolchain prints `char::to_lowercase`/`to_uppercase` for every
code point, so the tables reproduce exactly what the engine called before
(Unicode 17.0.0 for Rust 1.92). `Cased` and `Case_Ignorable`, which decide
the final-sigma context of `str::to_lowercase`, come from the regex crate's
property tables (`crates/regress-fork/src/unicodetables.rs`, also Unicode
17.0.0). The tests in special_casing.rs compare every code point against
the standard library, so a table that drifts from it fails there.

Encoding:
- CASE_LOWER / CASE_UPPER: sorted `(key, value)` runs. `key` is the first
  code point (bits 0-20), the run length minus one (bits 21-27), a stride-2
  flag (bit 28) and a multi-character flag (bit 29). A run maps each of its
  code points by adding `value`; a multi-character entry (length one) maps to
  row `value` of CASE_MULTI.
- CASE_MULTI: rows of three UTF-16 units, zero-padded (every multi-character
  mapping is in the BMP).
- CASED_RUNS/CASED_OFFSETS, CASE_IGNORABLE_RUNS/..._OFFSETS: the skip lists
  of `core::unicode::unicode_data` (the same search, the same layout).
"""
import argparse
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, 'crates', 'zipp-vm', 'src', 'vm', 'special_casing.rs')
UNICODE_TABLES = os.path.join(ROOT, 'crates', 'regress-fork', 'src', 'unicodetables.rs')
BEGIN = '// BEGIN GENERATED by tools/gen_case_tables.py: do not edit by hand.'
END = '// END GENERATED by tools/gen_case_tables.py'

DUMP = r'''
fn main() {
    println!("{}.{}.{}", char::UNICODE_VERSION.0, char::UNICODE_VERSION.1, char::UNICODE_VERSION.2);
    for c in 0..0x110000u32 {
        let Some(ch) = char::from_u32(c) else { continue };
        let l: Vec<u32> = ch.to_lowercase().map(|x| x as u32).collect();
        let u: Vec<u32> = ch.to_uppercase().map(|x| x as u32).collect();
        if l != [c] || u != [c] {
            let f = |v: &[u32]| v.iter().map(|x| format!("{:X}", x)).collect::<Vec<_>>().join(" ");
            println!("{:X};{};{}", c, f(&l), f(&u));
        }
    }
}
'''


def dump_mappings(toolchain):
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, 'dump.rs')
        exe = os.path.join(d, 'dump.exe' if os.name == 'nt' else 'dump')
        with open(src, 'w') as f:
            f.write(DUMP)
        subprocess.run(['rustc', toolchain, '-O', src, '-o', exe], check=True)
        out = subprocess.run([exe], check=True, capture_output=True, text=True).stdout
    lines = out.splitlines()
    version = lines[0]
    rows = []
    for line in lines[1:]:
        c, l, u = line.split(';')
        rows.append((int(c, 16), [int(x, 16) for x in l.split()], [int(x, 16) for x in u.split()]))
    return version, rows


def property_ranges(name):
    text = open(UNICODE_TABLES, encoding='utf-8').read()
    m = re.search(r'const %s: PackedIntervals = packed_intervals!\[(.*?)\];' % name, text, re.S)
    assert m, name
    ivs = [(int(a), int(b)) for a, b in re.findall(r'Interval::new\((\d+), (\d+)\)', m.group(1))]
    assert ivs == sorted(ivs)
    # Half-open ranges, adjacent intervals merged.
    out = []
    for a, b in ivs:
        if out and out[-1][1] == a:
            out[-1] = (out[-1][0], b + 1)
        else:
            out.append((a, b + 1))
    return out


def skiplist(ranges):
    """core's unicode-table-generator skiplist: (runs, offsets)."""
    points = [p for r in ranges for p in r]
    offsets = []
    prev = 0
    for p in points:
        offsets.append(p - prev)
        prev = p
    offsets.append(0x110000)
    coded, runs = [], []
    it = iter(offsets)
    prefix = 0
    while True:
        any_elements = inserted = False
        start = len(coded)
        for off in it:
            any_elements = True
            prefix += off
            if off < 256:
                coded.append(off)
            else:
                assert start < (1 << 11) and prefix < (1 << 21)
                runs.append((start << 21) | prefix)
                coded.append(0)
                inserted = True
                break
        if not any_elements:
            break
        assert inserted
    return runs, coded


def skip_search(c, runs, offsets):
    """The lookup, as the Rust side does it (used to self-check the encoding)."""
    key = (c << 11) & 0xFFFFFFFF
    lo, hi = 0, len(runs)
    while lo < hi:
        mid = (lo + hi) // 2
        if ((runs[mid] << 11) & 0xFFFFFFFF) <= key:
            lo = mid + 1
        else:
            hi = mid
    last = lo
    idx = runs[last] >> 21
    end = (runs[last + 1] >> 21) if last + 1 < len(runs) else len(offsets)
    prev = runs[last - 1] & 0x1FFFFF if last else 0
    total = c - prev
    s = 0
    for _ in range(end - idx - 1):
        s += offsets[idx]
        if s > total:
            break
        idx += 1
    return idx % 2 == 1


def runs_for(rows, which, multi):
    singles = []
    for row in rows:
        c, m = row[0], row[which]
        if m == [c]:
            continue
        if len(m) == 1:
            singles.append((c, m[0] - c))
        else:
            if m not in multi:
                multi.append(m)
            singles.append((c, None, multi.index(m)))
    entries = []
    i = 0
    while i < len(singles):
        s = singles[i]
        if s[1] is None:
            entries.append(((1 << 29) | s[0], s[2]))
            i += 1
            continue
        c, d = s
        best_len, best_stride = 1, 1
        for stride in (1, 2):
            j = i + 1
            while (j < len(singles) and j - i < 128 and singles[j][1] == d
                   and singles[j][0] == c + stride * (j - i)):
                j += 1
            if j - i > best_len:
                best_len, best_stride = j - i, stride
        key = c | ((best_len - 1) << 21) | ((1 if best_stride == 2 else 0) << 28)
        entries.append((key, d))
        i += best_len
    # Spans must not overlap: a lookup reads only the last run starting at or
    # before the code point.
    for (k1, _), (k2, _) in zip(entries, entries[1:]):
        start1, len1, s1 = k1 & 0x1FFFFF, ((k1 >> 21) & 0x7F) + 1, 2 if (k1 >> 28) & 1 else 1
        assert start1 + s1 * (len1 - 1) < (k2 & 0x1FFFFF), hex(start1)
    return entries


def lookup(entries, multi, c):
    keys = [k & 0x1FFFFF for k, _ in entries]
    lo, hi = 0, len(keys)
    while lo < hi:
        mid = (lo + hi) // 2
        if keys[mid] <= c:
            lo = mid + 1
        else:
            hi = mid
    if lo == 0:
        return [c]
    k, v = entries[lo - 1]
    off = c - (k & 0x1FFFFF)
    if (k >> 28) & 1:
        if off & 1:
            return [c]
        off >>= 1
    if off > (k >> 21) & 0x7F:
        return [c]
    if (k >> 29) & 1:
        return [u for u in multi[v] if u]
    return [c + v]


def fmt_list(items, per_line):
    lines = []
    for i in range(0, len(items), per_line):
        lines.append('    ' + ' '.join(items[i:i + per_line]))
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--toolchain', default='+1.92.0')
    ap.add_argument('--target', default=TARGET, help='the file to splice the tables into')
    a = ap.parse_args()
    version, rows = dump_mappings(a.toolchain)
    multi = []
    lower = runs_for(rows, 1, multi)
    upper = runs_for(rows, 2, multi)
    for m in multi:
        assert len(m) <= 3 and all(u <= 0xFFFF for u in m)
    multi_rows = [m + [0] * (3 - len(m)) for m in multi]
    by_cp = {r[0]: r for r in rows}
    for c in range(0x110000):
        if 0xD800 <= c < 0xE000:
            continue
        r = by_cp.get(c, (c, [c], [c]))
        assert lookup(lower, multi_rows, c) == r[1], hex(c)
        assert lookup(upper, multi_rows, c) == r[2], hex(c)
    props = {}
    for name in ('CASED', 'CASE_IGNORABLE'):
        ranges = property_ranges(name)
        runs, offsets = skiplist(ranges)
        inside = set()
        for lo_, hi_ in ranges:
            inside.update(range(lo_, hi_))
        for c in range(0x110000):
            assert skip_search(c, runs, offsets) == (c in inside), (name, hex(c))
        props[name] = (runs, offsets)

    out = [BEGIN, '// Default case mappings of Rust %s (Unicode %s), and the `Cased` and' % (a.toolchain.lstrip('+'), version),
           '// `Case_Ignorable` properties of the regex crate\'s tables (see the generator).',
           '#[rustfmt::skip]',
           'static CASE_LOWER: [(u32, i32); %d] = [' % len(lower),
           fmt_list(['(0x%X, %d),' % e for e in lower], 6), '];',
           '#[rustfmt::skip]',
           'static CASE_UPPER: [(u32, i32); %d] = [' % len(upper),
           fmt_list(['(0x%X, %d),' % e for e in upper], 6), '];',
           '#[rustfmt::skip]',
           'static CASE_MULTI: [[u16; 3]; %d] = [' % len(multi_rows),
           fmt_list(['[0x%X, 0x%X, 0x%X],' % tuple(m) for m in multi_rows], 4), '];']
    for name, rust in (('CASED', 'CASED'), ('CASE_IGNORABLE', 'CASE_IGNORABLE')):
        runs, offsets = props[name]
        out += ['#[rustfmt::skip]',
                'static %s_RUNS: [u32; %d] = [' % (rust, len(runs)),
                fmt_list(['0x%X,' % r for r in runs], 8), '];',
                '#[rustfmt::skip]',
                'static %s_OFFSETS: [u8; %d] = [' % (rust, len(offsets)),
                fmt_list(['%d,' % o for o in offsets], 20), '];']
    out.append(END)
    src = open(a.target, 'rb').read().decode('utf-8')
    # Keep the file's line endings (CRLF in a Windows checkout).
    nl = '\r\n' if '\r\n' in src else '\n'
    block = nl.join(nl.join(x.split('\n')) for x in out)
    if BEGIN in src:
        i = src.index(BEGIN)
        j = src.index(END) + len(END)
        src = src[:i] + block + src[j:]
    else:
        sys.exit('markers not found in ' + a.target)
    open(a.target, 'wb').write(src.encode('utf-8'))
    print('lower runs', len(lower), 'upper runs', len(upper), 'multi', len(multi_rows),
          'cased', [len(x) for x in props['CASED']], 'case_ignorable', [len(x) for x in props['CASE_IGNORABLE']])


if __name__ == '__main__':
    main()
