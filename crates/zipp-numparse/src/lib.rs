// `opt-level = "z"`, which leaves `RangeInclusive::contains` as a call.
#![allow(clippy::manual_range_contains)]

use num_bigint::BigUint;
use num_traits::{Euclid, ToPrimitive};
use std::sync::OnceLock;

const INFINITY_BITS: u64 = 0x7FF0_0000_0000_0000;
const MANTISSA_MASK: u64 = (1 << 52) - 1;

/// Core's `SMALLEST_POWER_OF_FIVE` and `LARGEST_POWER_OF_FIVE`: below `q =
/// -342` nineteen digits round to zero, above `q = 308` one digit is already
/// infinite.
const MIN_Q: i64 = -342;
const MAX_Q: i64 = 308;
const TABLE_LEN: usize = (MAX_Q - MIN_Q + 1) as usize;

/// The smallest integer of 19 digits, `10^18`.
const MIN_19_DIGITS: u64 = 1_000_000_000_000_000_000;

/// The powers of ten that are exact doubles.
const POW10: [f64; 23] = [
    1e0, 1e1, 1e2, 1e3, 1e4, 1e5, 1e6, 1e7, 1e8, 1e9, 1e10, 1e11, 1e12, 1e13, 1e14, 1e15, 1e16,
    1e17, 1e18, 1e19, 1e20, 1e21, 1e22,
];

/// Significant digits the exact fallback reads; anything after them matters
/// only as "some later digit is not zero". The value halfway between two
/// adjacent doubles has at most 768 significant digits (the longest are just
/// above `f64::MIN_POSITIVE`), so with at least that many digits kept no such
/// halfway point can lie strictly between the kept digits and the kept digits
/// plus one unit: replacing the tail by a single `1` rounds the same way.
/// 768 is also core's cutoff (`DecimalSeq::MAX_DIGITS`); the spare digits
/// here cost nothing.
const EXACT_DIGITS: usize = 800;

/// `s.parse::<f64>().ok()`, without core's table.
#[inline]
pub fn parse_f64(s: &str) -> Option<f64> {
    parse_f64_bytes(s.as_bytes())
}

/// [`parse_f64`] for a caller that holds bytes. Every accepted input is
/// ASCII, so anything that is not UTF-8 is rejected like any other stray
/// byte, and no caller needs a UTF-8 pass first.
pub fn parse_f64_bytes(s: &[u8]) -> Option<f64> {
    let (negative, body) = match s.split_first()? {
        (b'-', rest) => (true, rest),
        (b'+', rest) => (false, rest),
        _ => (false, s),
    };
    let magnitude = match number(body) {
        Some(bits) => f64::from_bits(bits),
        None => inf_or_nan(body)?,
    };
    Some(if negative { -magnitude } else { magnitude })
}

/// The words core accepts after the optional sign, in any ASCII case.
fn inf_or_nan(s: &[u8]) -> Option<f64> {
    const NAN: u64 = u64::from_be_bytes(*b"\0\0\0\0\0nan");
    const INF: u64 = u64::from_be_bytes(*b"\0\0\0\0\0inf");
    const INFINITY: u64 = u64::from_be_bytes(*b"infinity");
    if s.len() > 8 {
        return None;
    }
    // The bytes as one big-endian word. `| 0x20` makes an ASCII capital its
    // small letter, makes no other byte a letter it was not, and never
    // yields zero, so only text of a word's own length can equal the word.
    let mut word = 0u64;
    for &c in s {
        word = word << 8 | u64::from(c | 0x20);
    }
    match word {
        NAN => Some(f64::NAN),
        INF | INFINITY => Some(f64::INFINITY),
        _ => None,
    }
}

/// The bits of the double nearest to an unsigned decimal number, or `None`
/// when `s` is not one:
///
/// ```txt
/// Number ::= ( Digit+ | Digit+ '.' Digit* | Digit* '.' Digit+ ) Exp?
/// Exp    ::= ('e' | 'E') ('+' | '-')? Digit+
/// ```
fn number(s: &[u8]) -> Option<u64> {
    // The mantissa in one pass: digits around at most one point. The first
    // 19 significant digits always fit a `u64` (`w`); `dropped` counts the
    // digits after those, and `inexact` says one of them was not zero.
    let (mut w, mut dropped, mut inexact) = (0u64, 0i64, false);
    let (mut end, mut point) = (0, None);
    while end < s.len() {
        let digit = s[end].wrapping_sub(b'0');
        if digit <= 9 {
            if w < MIN_19_DIGITS {
                // Fewer than 19 digits so far (leading zeros leave `w` at
                // zero), so one more cannot overflow. Written as wrapping
                // because the WebAssembly modules check overflow, and a
                // checked 64-bit multiplication there is a call to a
                // 128-bit one, once per digit.
                w = w.wrapping_mul(10).wrapping_add(u64::from(digit));
            } else {
                dropped += 1;
                inexact |= digit != 0;
            }
        } else if s[end] == b'.' && point.is_none() {
            point = Some(end);
        } else {
            break;
        }
        end += 1;
    }
    let (digits, frac_len) = match point {
        Some(point) => (end - 1, end - point - 1),
        None => (end, 0),
    };
    if digits == 0 {
        return None;
    }
    let (mantissa, rest) = s.split_at_checked(end)?;
    let mut exp: i32 = 0;
    if let Some((b'e' | b'E', rest)) = rest.split_first() {
        let (negative, exp_digits) = match rest.split_first() {
            Some((b'-', exp_digits)) => (true, exp_digits),
            Some((b'+', exp_digits)) => (false, exp_digits),
            _ => (false, rest),
        };
        if exp_digits.is_empty() {
            return None;
        }
        for &c in exp_digits {
            let digit = c.wrapping_sub(b'0');
            if digit > 9 {
                return None;
            }
            // Core's rule, kept exactly: the exponent stops growing here
            // rather than saturating at a limit, so an absurd exponent is
            // whatever its leading digits spell. Only a mantissa tens of
            // thousands of digits long can tell the difference, and for
            // that input this returns what core returns.
            if exp < 0x10000 {
                exp = exp * 10 + i32::from(digit);
            }
        }
        if negative {
            exp = -exp;
        }
    } else if !rest.is_empty() {
        return None;
    }

    if w == 0 {
        return Some(0);
    }
    // The mantissa's digits read as one integer, times 10^exp10, is the
    // number; `w * 10^q` is the number with its tail cut off.
    let exp10 = i64::from(exp) - frac_len as i64;
    let q = exp10 + dropped;

    if w <= 1 << 53 {
        if q >= -22 && q <= 22 {
            let power = POW10[q.unsigned_abs() as usize];
            let value = if q < 0 {
                w as f64 / power
            } else {
                w as f64 * power
            };
            return Some(value.to_bits());
        }
        if q > 22 && q <= 37 {
            // Move the surplus powers of ten into the integer when the
            // product is still an exact double.
            let surplus = POW10[(q - 22) as usize] as u64;
            if w <= (1 << 53) / surplus {
                return Some((w.wrapping_mul(surplus) as f64 * POW10[22]).to_bits());
            }
        }
    }

    let mut bits = eisel_lemire(q, w);
    if inexact && bits.is_some() && bits != eisel_lemire(q, w + 1) {
        bits = None;
    }
    Some(match bits {
        Some(bits) => bits,
        None => exact(mantissa, exp10),
    })
}

/// The bits of the double nearest to `w * 10^q`, or `None` when the 128-bit
/// product is too close to a rounding boundary to tell. Port of core's
/// `compute_float::<f64>`; its `BiasedFp` is returned already packed.
fn eisel_lemire(q: i64, mut w: u64) -> Option<u64> {
    if w == 0 || q < MIN_Q {
        return Some(0);
    } else if q > MAX_Q {
        return Some(INFINITY_BITS);
    }
    // Normalize the significant digits, so the most-significant bit is set.
    let lz = w.leading_zeros();
    w <<= lz;
    let (lo, hi) = product_approx(q, w);
    if lo == u64::MAX && (q < -27 || q > 55) {
        // The 128-bit multiplier was not enough: adding one to `lo` could
        // carry into `hi` and across the halfway point. Inside [-27, 55]
        // the product is exact or cannot land on a tie, so it stands.
        return None;
    }
    let upperbit = (hi >> 63) as i32;
    // 54 bits: the 53 of the result and one to round with.
    let mut mantissa = hi >> (upperbit + 9);
    let mut power2 = power(q as i32) + upperbit - lz as i32 + 1023;
    if power2 <= 0 {
        if -power2 + 1 >= 64 {
            // More than 64 bits below the smallest exponent: zero.
            return Some(0);
        }
        // Subnormal. Rounding up to 2^52 lands on the smallest normal
        // number, whose bits are that same integer.
        mantissa >>= -power2 + 1;
        mantissa += mantissa & 1;
        mantissa >>= 1;
        return Some(mantissa);
    }
    // A tie rounds to even instead of up. It can only be a tie when 5^q fits
    // one word (so `lo` says the product is exact), the bit below the result
    // is the only one set, and nothing was shifted out.
    if lo <= 1
        && q >= -4
        && q <= 23
        && mantissa & 0b11 == 0b01
        && (mantissa << (upperbit + 9)) == hi
    {
        mantissa &= !1;
    }
    mantissa += mantissa & 1;
    mantissa >>= 1;
    if mantissa >= 2 << 52 {
        // Rounding up carried out of the 53 bits.
        mantissa = 1 << 52;
        power2 += 1;
    }
    mantissa &= MANTISSA_MASK;
    if power2 >= 0x7FF {
        return Some(INFINITY_BITS);
    }
    Some(mantissa | (power2 as u64) << 52)
}

/// The binary exponent of `10^q`'s leading bit: `floor(q * log2(10)) + 63`,
/// with 217706 / 2^16 for the logarithm, which is exact over the table's
/// range.
fn power(q: i32) -> i32 {
    (q.wrapping_mul(152_170 + 65536) >> 16) + 63
}

/// `(low, high)` words of `w * 5^q` scaled to 128 bits, good to the 55 bits
/// the caller needs unless `low` comes back all ones.
fn product_approx(q: i64, w: u64) -> (u64, u64) {
    // 55 = 52 explicit bits, the hidden bit, one to round on and one for a
    // product with a leading zero.
    const MASK: u64 = u64::MAX >> 55;
    let (five_hi, five_lo) = powers_of_five()[(q - MIN_Q) as usize];
    let first = u128::from(w) * u128::from(five_hi);
    let (mut first_lo, mut first_hi) = (first as u64, (first >> 64) as u64);
    if first_hi & MASK == MASK {
        // The bits that decide the rounding are all ones, so the second
        // word of the multiplier matters.
        let second_hi = ((u128::from(w) * u128::from(five_lo)) >> 64) as u64;
        first_lo = first_lo.wrapping_add(second_hi);
        if second_hi > first_lo {
            first_hi += 1;
        }
    }
    (first_lo, first_hi)
}

/// Core's `POWER_OF_FIVE_128`: for each `q` in `[-342, 308]`, a 128-bit
/// approximation of `5^q` with its top bit set, as `(high, low)` words.
fn powers_of_five() -> &'static [(u64, u64); TABLE_LEN] {
    static TABLE: OnceLock<Box<[(u64, u64); TABLE_LEN]>> = OnceLock::new();
    TABLE.get_or_init(build_powers_of_five)
}

// The big-integer steps of the two cold paths. Each is one small function
// that is never inlined: in the modules built for speed the compiler would
// otherwise expand num-bigint's loops at every use, and these paths run
// once (the table) or rarely (`exact`), so a call is the right price.

/// `n = n * 2^bits`.
#[inline(never)]
fn shl(n: &mut BigUint, bits: usize) {
    *n <<= bits;
}

/// `2^n`.
#[inline(never)]
fn pow2(n: usize) -> BigUint {
    let mut power = BigUint::from(1u32);
    shl(&mut power, n);
    power
}

/// `n = n * mul + add`.
#[inline(never)]
fn mul_add(n: &mut BigUint, mul: u32, add: u32) {
    *n *= mul;
    *n += add;
}

/// `n / d` rounded down, and whether anything was left over.
#[inline(never)]
fn div(n: &BigUint, d: &BigUint) -> (BigUint, bool) {
    let (quotient, remainder) = n.div_rem_euclid(d);
    (quotient, remainder.bits() != 0)
}

/// The table, as rustc's `src/etc/dec2flt_table.py` generates it.
///
/// For `q >= 0` an entry is the top 128 bits of `5^q`, truncated. For `q < 0`
/// it is `2^b / 5^-q + 1` (the reciprocal, rounded up), with `z` the bit
/// length of `5^-q`: `b = z + 127` down to `q = -27`, where that quotient is
/// 128 bits long as it stands, and `b = 2z + 128` below, where it is longer
/// and is truncated to its top 128 bits. Every truncation here is a division
/// by a power of two, so that the one division routine does all the work.
#[cold]
#[inline(never)]
fn build_powers_of_five() -> Box<[(u64, u64); TABLE_LEN]> {
    const ZERO_Q: usize = (-MIN_Q) as usize;
    let mut table = Box::new([(0u64, 0u64); TABLE_LEN]);
    let mut power = BigUint::from(1u32); // 5^k
    let mut shifted = pow2(128); // 5^k * 2^128
    for k in 0..=ZERO_Q {
        let z = power.bits() as usize;
        let b = if k <= 27 { z + 127 } else { 2 * z + 128 };
        let (mut reciprocal, _) = div(&pow2(b), &power);
        mul_add(&mut reciprocal, 1, 1); // + 1
        let surplus = (reciprocal.bits() as usize).saturating_sub(128);
        // 5^-k, then 5^k: for k = 0 the second, which is the right one,
        // overwrites the first, and past 5^308 it has no slot.
        let entries = [
            (ZERO_Q - k, &reciprocal, surplus),
            (ZERO_Q + k, &shifted, z),
        ];
        for (index, value, cut) in entries {
            let (entry, _) = div(value, &pow2(cut));
            if let (Some(slot), Some(entry)) = (table.get_mut(index), entry.to_u128()) {
                *slot = ((entry >> 64) as u64, entry as u64);
            }
        }
        mul_add(&mut power, 5, 0);
        mul_add(&mut shifted, 5, 0);
    }
    table
}

/// The exact answer for the few inputs Eisel-Lemire cannot settle: the bits
/// of the double nearest to the digits of `mantissa` (which may hold one
/// `.`), read as an integer, times `10^exp10`; ties go to even.
///
/// Only reached for a value inside the table's range, so `exp10` is at most a
/// few hundred above zero and at most about 1,150 below, and the work is
/// bounded however long the input is.
#[cold]
#[inline(never)]
fn exact(mantissa: &[u8], mut exp10: i64) -> u64 {
    // The significant digits as one integer, nine digits (one `u32`) at a
    // time.
    let mut num = BigUint::ZERO;
    let (mut chunk, mut chunk_scale) = (0u32, 1u32);
    let (mut kept, mut tail) = (0usize, false);
    for &c in mantissa {
        if c == b'.' {
            continue;
        }
        let mut digit = u32::from(c.wrapping_sub(b'0'));
        if kept == EXACT_DIGITS {
            // Past the cutoff a digit only moves the exponent, except the
            // first that is not zero: it stands for the whole tail, as one
            // more digit, a 1 (see `EXACT_DIGITS`).
            exp10 += 1;
            if digit == 0 || tail {
                continue;
            }
            tail = true;
            digit = 1;
            exp10 -= 1;
        } else if digit != 0 || kept != 0 {
            kept += 1;
        } else {
            continue; // a leading zero
        }
        chunk = chunk * 10 + digit;
        chunk_scale *= 10;
        if chunk_scale == 1_000_000_000 {
            mul_add(&mut num, chunk_scale, chunk);
            (chunk, chunk_scale) = (0, 1);
        }
    }
    mul_add(&mut num, chunk_scale, chunk);

    // The value is num / den * 2^exp10 once 5^|exp10| is on the side its
    // sign puts it; 5^13 is the largest power in a `u32`.
    let mut den = BigUint::from(1u32);
    let side = if exp10 < 0 { &mut den } else { &mut num };
    let mut fives = exp10.unsigned_abs() as u32;
    while fives > 0 {
        let step = fives.min(13);
        mul_add(side, 5u32.wrapping_pow(step), 0);
        fives -= step;
    }
    // Scale by a power of two so the quotient has 55 or 56 bits: 53 for the
    // result and at least two to round on.
    let scale = 55 - (num.bits() as i64 - den.bits() as i64);
    let side = if scale < 0 { &mut den } else { &mut num };
    shl(side, scale.unsigned_abs() as usize);
    let (quotient, remainder) = div(&num, &den);
    round(quotient.to_u64().unwrap_or(0), remainder, exp10 - scale)
}

/// The bits of the double nearest to a value known as a quotient of 55 or 56
/// bits: `quotient * 2^lsb <= value < (quotient + 1) * 2^lsb`, with
/// `remainder` saying that it is not the lower bound itself.
fn round(quotient: u64, remainder: bool, lsb: i64) -> u64 {
    // The value's leading bit is 2^exp2.
    let len = 64 - i64::from(quotient.leading_zeros());
    let exp2 = lsb + len - 1;
    if exp2 > 1023 {
        return INFINITY_BITS;
    }
    // Bits of the quotient below the result's last place. A subnormal's last
    // place is fixed at 2^-1074.
    let subnormal = exp2 < -1022;
    let below = if subnormal { -1074 - lsb } else { len - 53 };
    if below < 1 || below > 57 {
        // Less than a quarter of the smallest subnormal.
        return 0;
    }
    let result = quotient >> below;
    let rest = quotient & ((1 << below) - 1);
    let half = 1 << (below - 1);
    let round_up = rest > half || (rest == half && (remainder || result & 1 == 1));
    let bits = if subnormal {
        result
    } else {
        ((exp2 + 1023) as u64) << 52 | (result & MANTISSA_MASK)
    };
    // The next double up is the next integer, across a binade and into
    // infinity alike.
    bits + u64::from(round_up)
}

