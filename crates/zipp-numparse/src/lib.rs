//! Decimal text to `f64`: ZIPP's one string-to-number conversion.
//!
//! [`parse_f64`] returns, for every input, exactly what
//! `s.parse::<f64>().ok()` returns: the same accepted grammar and the same
//! correctly rounded bits. The engine's numeric literals, `Number(str)`,
//! `parseFloat`, `JSON.parse` and the rest, and the Python front end's float
//! literals, all end here instead of in core's parser.
//!
//! The reason is one table. `core::num::dec2flt` reads the Eisel-Lemire
//! multipliers from `POWER_OF_FIVE_128`, 651 pairs of `u64` (10,416 bytes) in
//! read-only data. The table is high-entropy, so Brotli keeps almost all of
//! it: about 10 KB of every shipped WebAssembly module, the largest
//! incompressible item in the artifact, and nothing in core lets a build
//! leave it out. This crate computes the same 651 entries at first use with
//! `num-bigint`, which the engine links anyway for BigInt, and keeps them on
//! the heap. It is a crate of its own, not a module of `zipp-vm`, because
//! `zipp-pyparse` cannot depend on the engine and one `parse::<f64>()` in
//! either links core's table back in. A test in `zipp-vm`
//! (`num_parse::tests::no_core_float_parse_in_engine_sources`) reads both
//! crates' sources and the WebAssembly embedding's for such a call.
//!
//! The conversion, cheapest step first:
//!
//! 1. Check the text against core's grammar and gather the first 19
//!    significant digits into a `u64` (`w`) with a decimal exponent (`q`),
//!    noting whether a non-zero digit was left out.
//! 2. Clinger's exact path: when `w <= 2^53` and `|q| <= 22` both operands
//!    are exact doubles, so one multiplication or division is the correctly
//!    rounded answer (also for `q` up to 37 when the extra powers of ten fit
//!    into `w`). Most numbers in real programs stop here and never touch the
//!    table.
//! 3. Eisel-Lemire: `w` times a 128-bit approximation of `5^q` decides the
//!    rounding for nearly everything else. When digits were left out, `w` and
//!    `w + 1` bracket the value; if both round to the same double, so does
//!    the value.
//! 4. Otherwise (Eisel-Lemire reports that it cannot decide, or the two
//!    brackets differ) the digits are divided exactly as big integers and the
//!    quotient is rounded to nearest, ties to even.
//!
//! What derives from core (Rust 1.92, `library/core/src/num/dec2flt`, MIT OR
//! Apache-2.0):
//!
//! - `eisel_lemire`, `product_approx` and `power` are ports of
//!   `lemire.rs` (`compute_float` and its helpers) with the `f64` constants
//!   of `float.rs` written in. They are kept line for line because bit
//!   exactness depends on every shift in them.
//! - The grammar in `number` follows `parse.rs`, including the way an
//!   explicit exponent stops accumulating past `0x10000`, and the fast
//!   path's bounds follow `decimal.rs`.
//! - The table is generated by the method of rustc's
//!   `src/etc/dec2flt_table.py`, the script that produced core's `table.rs`.
//!
//! The exact fallback is not core's: core shifts a 768-digit decimal buffer
//! bit by bit (`decimal_seq.rs`, `slow.rs`); this divides with `num-bigint`.
//! Both are exact, so they agree. No `unsafe`: the crate forbids it, as the
//! WebAssembly modules require of everything they link.
//!
//! The two cold functions (`exact` and `build_powers_of_five`) keep to three
//! big-integer operations on purpose (multiply by a `u32` and add one, shift
//! left, divide with remainder): each further kind of operation is another
//! instantiation in the module, and bytes are what this file is for. Being
//! another crate has a price here: num-bigint's `#[inline]` helpers are
//! compiled into each crate that calls them, so the few this file uses exist
//! twice in a module, about 1.4 KB in Lite. Writing the big-integer steps
//! here instead, as loops over 32-bit limbs, measured larger still (its own
//! loops and bounds checks against helpers the engine already has).

#![forbid(unsafe_code)]
