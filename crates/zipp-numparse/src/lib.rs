    fn fnv1a(table: &[(u64, u64)]) -> u64 {
        let mut hash = 0xcbf2_9ce4_8422_2325u64;
        for &(hi, lo) in table {
            for byte in hi.to_le_bytes().into_iter().chain(lo.to_le_bytes()) {
                hash = (hash ^ u64::from(byte)).wrapping_mul(0x0000_0100_0000_01b3);
            }
        }
        hash
    }

