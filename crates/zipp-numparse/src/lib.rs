    /// The decimal digits of the value halfway between the positive double
    /// with these fields and the next one up, and the power of ten to
    /// multiply them by.
    fn midpoint(biased: u64, fraction: u64) -> (BigUint, i64) {
        let (m, e) = if biased == 0 {
            (fraction, -1074)
        } else {
            (fraction | 1 << 52, biased as i64 - 1075)
        };
        let odd = BigUint::from(2 * m + 1); // the midpoint is odd * 2^(e-1)
        if e > 0 {
            (odd << (e - 1) as usize, 0)
        } else {
            (odd * BigUint::from(5u32).pow((1 - e) as u32), e - 1)
        }
    }

    /// Inputs far longer than the exact path reads: only "is the tail zero"
    /// may matter, and it must matter.
    #[test]
    fn digits_past_the_cutoff_are_a_sticky_bit() {
        let mut s = String::new();
        // The longest midpoints (768 digits) sit just above MIN_POSITIVE;
        // also a subnormal, an ordinary double, and the overflow threshold.
        for (biased, fraction) in [
            (1, MANTISSA_MASK),
            (1, 0),
            (0, MANTISSA_MASK),
            (0, 1),
            (0, 0),
            (1023, 0),
            (1023, 0x3_3333_3333_3333),
            (2046, MANTISSA_MASK),
        ] {
            let (digits, exp10) = midpoint(biased, fraction);
            let below = (&digits - 1u32).to_string();
            let digits = digits.to_string();
            for pad in [0usize, 1, 31, 32, 33, 40, 800, 1000, 5000] {
                for tail in ["", "1", "9"] {
                    // The tie, then zeros, then maybe something.
                    s.clear();
                    s.push_str(&digits);
                    s.extend(std::iter::repeat_n('0', pad));
                    s.push_str(tail);
                    let shift = exp10 - (pad + tail.len()) as i64;
                    write!(s, "e{shift}").unwrap();
                    check(&s);
                    // Just under the tie, then nines.
                    s.clear();
                    s.push_str(&below);
                    s.extend(std::iter::repeat_n('9', pad));
                    s.push_str(tail);
                    write!(s, "e{shift}").unwrap();
                    check(&s);
                    // The same digits written as a plain fraction.
                    if exp10 < 0 {
                        s.clear();
                        plain(&mut s, &digits, exp10);
                        s.extend(std::iter::repeat_n('0', pad));
                        s.push_str(tail);
                        check(&s);
                    }
                }
            }
        }
    }

