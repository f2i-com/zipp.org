    /// xorshift64*, seeded: a failure reproduces from its seed and index.
    struct Rng(u64);

    impl Rng {
        fn next(&mut self) -> u64 {
            self.0 ^= self.0 >> 12;
            self.0 ^= self.0 << 25;
            self.0 ^= self.0 >> 27;
            self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
        }

        fn below(&mut self, n: usize) -> usize {
            (self.next() % n as u64) as usize
        }

        /// Inclusive at both ends.
        fn between(&mut self, low: i64, high: i64) -> i64 {
            low + (self.next() % (high - low + 1) as u64) as i64
        }

        fn digits(&mut self, s: &mut String, n: usize) {
            for _ in 0..n {
                s.push(char::from(b'0' + self.below(10) as u8));
            }
        }

        fn sign(&mut self, s: &mut String) {
            match self.below(8) {
                0 | 1 => s.push('-'),
                2 => s.push('+'),
                _ => {}
            }
        }
    }

    /// `digits * 10^exp10` in one of three spellings: scientific with no
    /// point, scientific with a point anywhere, or plain positional.
    fn spell(r: &mut Rng, s: &mut String, digits: &str, exp10: i64) {
        match r.below(3) {
            0 => write!(s, "{digits}e{exp10}").unwrap(),
            1 => {
                let point = r.below(digits.len() + 1);
                let (int, frac) = digits.split_at(point);
                write!(s, "{int}.{frac}e{}", exp10 + frac.len() as i64).unwrap();
            }
            _ => plain(s, digits, exp10),
        }
    }

    /// `digits * 10^exp10` written without an exponent.
    fn plain(s: &mut String, digits: &str, exp10: i64) {
        let len = digits.len() as i64;
        if exp10 >= 0 {
            s.push_str(digits);
            s.extend(std::iter::repeat_n('0', exp10 as usize));
        } else if -exp10 < len {
            let (int, frac) = digits.split_at((len + exp10) as usize);
            write!(s, "{int}.{frac}").unwrap();
        } else {
            s.push_str("0.");
            s.extend(std::iter::repeat_n('0', (-exp10 - len) as usize));
            s.push_str(digits);
        }
    }

    /// Short decimals in every legal shape (`1.`, `.5`, `1e5`, ...), and the
    /// illegal ones the same choices produce (`.`, an empty string).
    fn short_decimal(r: &mut Rng, s: &mut String) {
        r.sign(s);
        let (int, frac) = (r.below(7), r.below(7));
        r.digits(s, int);
        if frac > 0 || r.below(4) == 0 {
            s.push('.');
            r.digits(s, frac);
        }
        if r.below(3) == 0 {
            s.push(if r.below(2) == 0 { 'e' } else { 'E' });
            match r.below(4) {
                0 => s.push('-'),
                1 => s.push('+'),
                _ => {}
            }
            write!(s, "{}", r.below(40)).unwrap();
        }
    }

    /// A tie in few digits: `w * 10^q` exactly halfway between two doubles
    /// with `w` inside a `u64` and `q` from -4 to 23, the range where the
    /// power of five fits one word and Eisel-Lemire itself has to see the
    /// tie and round to even; and the integers either side of that `w`.
    fn short_tie(r: &mut Rng, s: &mut String) {
        r.sign(s);
        let q = r.between(-4, 23);
        let five = 5u64.pow(q.unsigned_abs() as u32);
        let w = if q >= 0 {
            // An odd multiple of 5^q with 54 bits is halfway between two
            // 53-bit integers, and stays a tie times any power of two.
            let (low, high) = ((1u64 << 53).div_ceil(five), ((1 << 54) - 1) / five);
            let odd = (low + r.next() % (high - low + 1)) | 1;
            odd << r.below(odd.leading_zeros() as usize)
        } else {
            // odd / 2^-q, written as (odd * 5^-q) / 10^-q.
            let high = ((1u64 << 54) - 1).min(9_999_999_999_999_999_999 / five);
            ((1 << 53) + r.next() % (high - (1 << 53)) | 1) * five
        };
        write!(s, "{}e{q}", w + r.below(5) as u64 / 2 - 1).unwrap();
    }

    /// 15 to 19 digits, the lengths where the `u64` fills up and the fast
    /// path ends, at every magnitude from below the smallest subnormal to
    /// above the largest double.
    fn long_mantissa(r: &mut Rng, s: &mut String) {
        r.sign(s);
        let len = 15 + r.below(5);
        let point = if r.below(2) == 0 {
            len
        } else {
            r.below(len + 1)
        };
        r.digits(s, point);
        if point < len {
            s.push('.');
            r.digits(s, len - point);
        }
        write!(s, "e{}", r.between(-345, 310) - point as i64).unwrap();
    }

    /// What the engine itself prints for a random double: the shortest
    /// digits that read back as it, in scientific and in positional form
    /// (hundreds of digits for the largest and smallest values).
    fn round_trip(r: &mut Rng, s: &mut String) {
        let bits = match r.below(8) {
            0 => r.next() & MANTISSA_MASK,             // subnormal
            1 => r.next() & (MANTISSA_MASK | 3 << 52), // up to the first normal binades
            2 => r.next() | 0x7FC0_0000_0000_0000,     // the top binades, inf, NaN
            _ => r.next(),
        };
        let value = f64::from_bits(bits);
        match r.below(3) {
            0 => write!(s, "{value:e}").unwrap(),
            1 => write!(s, "{value}").unwrap(),
            _ => write!(s, "{value:?}").unwrap(),
        }
    }

    /// The exact decimal expansion of the point halfway between two adjacent
    /// doubles, where the answer hangs on the last digit: the tie itself, a
    /// hair above it, a hair below it, and cut short.
    fn halfway(r: &mut Rng, s: &mut String) {
        let biased = match r.below(4) {
            0 => r.below(3) as u64,        // subnormals and the first normal binades
            1 => 2044 + r.below(3) as u64, // up to the overflow threshold
            _ => r.below(2047) as u64,
        };
        let fraction = match r.below(4) {
            0 => r.below(16) as u64,
            1 => MANTISSA_MASK - r.below(16) as u64,
            _ => r.next() & MANTISSA_MASK,
        };
        let (mut digits, mut exp10) = midpoint(biased, fraction);
        let mut nines = 0;
        match r.below(8) {
            0 | 1 => {}
            2 => {
                digits = digits * 10u32 + 1u32;
                exp10 -= 1;
            }
            3 => digits -= 1u32,
            4 => {
                let zeros = 1 + r.below(60);
                digits = digits * BigUint::from(10u32).pow(zeros as u32) + 1u32;
                exp10 -= zeros as i64;
            }
            5 => {
                digits -= 1u32;
                nines = 1 + r.below(60);
            }
            6 => digits += 1u32,
            _ => {}
        }
        let mut text = digits.to_string();
        text.extend(std::iter::repeat_n('9', nines));
        exp10 -= nines as i64;
        if r.below(8) == 7 {
            // A prefix of the expansion: the same question with the tail
            // gone, at a length that may be under or over 19 digits.
            let keep = 1 + r.below(text.len().min(40));
            exp10 += (text.len() - keep) as i64;
            text.truncate(keep);
        }
        spell(r, s, &text, exp10);
    }

    /// The edges of the format, with their digits disturbed: the subnormal
    /// range and `MIN_POSITIVE`, half the smallest subnormal (below it is
    /// zero), `MAX` and the overflow threshold above it, 2^53 and 2^64.
    fn boundary(r: &mut Rng, s: &mut String) {
        const TEXTS: [&str; 20] = [
            "4.9406564584124654e-324",
            "2.4703282292062327e-324",
            "2.4703282292062328e-324",
            "7.4109846876186981e-324",
            "2.2250738585072009e-308",
            "2.2250738585072011e-308",
            "2.2250738585072012e-308",
            "2.2250738585072014e-308",
            "4.4501477170144023e-308",
            "1.7976931348623157e308",
            "1.7976931348623158e308",
            "1.797693134862315807e308",
            "1.797693134862315708e308",
            "8.9884656743115795e307",
            "9007199254740992",
            "9007199254740993",
            "18446744073709551615",
            "18446744073709551616",
            "9999999999999999999",
            "1e23",
        ];
        const BITS: [u64; 6] = [
            0,
            MANTISSA_MASK,
            1 << 52,
            0x7FEF_FFFF_FFFF_FFFF,
            0x7FE0_0000_0000_0000,
            0x4340_0000_0000_0000,
        ];
        let mut text = String::new();
        if r.below(3) == 0 {
            let bits = BITS[r.below(BITS.len())] + r.below(9) as u64;
            write!(
                text,
                "{:e}",
                f64::from_bits(bits.saturating_sub(4).min(0x7FEF_FFFF_FFFF_FFFF))
            )
            .unwrap();
        } else {
            text.push_str(TEXTS[r.below(TEXTS.len())]);
        }
        let (mantissa, exp) = match text.split_once('e') {
            Some((mantissa, exp)) => (mantissa, exp.parse::<i64>().unwrap()),
            None => (&text[..], 0),
        };
        let mut mantissa = mantissa.as_bytes().to_vec();
        if r.below(2) == 0 {
            let at = r.below(mantissa.len());
            if mantissa[at].is_ascii_digit() {
                mantissa[at] = b'0' + r.below(10) as u8;
            }
        }
        let extra = [0, 0, 1, 2, 5, 25][r.below(6)];
        if extra > 0 && !mantissa.contains(&b'.') {
            mantissa.push(b'.');
        }
        s.push_str(std::str::from_utf8(&mantissa).unwrap());
        r.digits(s, extra);
        write!(s, "e{}", exp + r.between(-1, 1) / (1 + r.below(2) as i64)).unwrap();
    }

    /// 20 to 800 digits: past the `u64`, up to and past the 768 that a
    /// halfway point can need.
    fn long_digits(r: &mut Rng, s: &mut String) {
        r.sign(s);
        let len = 20 + r.below(781);
        let point = match r.below(3) {
            0 => len,
            1 => r.below(len + 1),
            _ => 0,
        };
        let start = s.len();
        match r.below(8) {
            0 => s.extend(std::iter::repeat_n('9', len)),
            1 => {
                // One digit, a long run of zeros, one digit.
                r.digits(s, 1);
                s.extend(std::iter::repeat_n('0', len - 2));
                r.digits(s, 1);
            }
            2 => {
                // Random digits, then nothing but zeros.
                let head = 1 + r.below(len - 1);
                r.digits(s, head);
                s.extend(std::iter::repeat_n('0', len - head));
            }
            _ => r.digits(s, len),
        }
        if point < len {
            s.insert(start + point, '.');
        }
        write!(s, "e{}", r.between(-345, 310) - point as i64).unwrap();
    }

    /// Zeros that are not significant (leading) and zeros that are
    /// (trailing), on both sides of the point.
    fn zeros(r: &mut Rng, s: &mut String) {
        r.sign(s);
        let (lead, len, trail) = (r.below(40), 1 + r.below(20), r.below(40));
        let start = s.len();
        s.extend(std::iter::repeat_n('0', lead));
        r.digits(s, len);
        s.extend(std::iter::repeat_n('0', trail));
        if r.below(4) != 0 {
            let at = start + r.below(lead + len + trail + 1);
            s.insert(at, '.');
        }
        match r.below(4) {
            0 => write!(s, "e{}", r.between(-360, 330)).unwrap(),
            1 => write!(s, "e{}", r.between(-30, 30)).unwrap(),
            _ => {}
        }
    }

    /// Text that is nearly a number.
    fn malformed(r: &mut Rng, s: &mut String) {
        const ALPHABET: &[u8] = b"0123456789+-..eEinfINFatyTYN_ x,";
        const WORDS: [&str; 10] = [
            "inf", "infinity", "nan", "Infinity", "NaN", "INF", "infinit", "nane", "in", "e",
        ];
        match r.below(3) {
            0 => {
                for _ in 0..r.below(13) {
                    s.push(char::from(ALPHABET[r.below(ALPHABET.len())]));
                }
                return;
            }
            1 => short_decimal(r, s),
            _ => {
                r.sign(s);
                for c in WORDS[r.below(WORDS.len())].chars() {
                    s.push(if r.below(3) == 0 {
                        c.to_ascii_uppercase()
                    } else {
                        c
                    });
                }
            }
        }
        if r.below(3) != 0 {
            let junk = char::from(ALPHABET[r.below(ALPHABET.len())]);
            let at = r.below(s.len() + 1);
            if r.below(2) == 0 || at == s.len() {
                s.insert(at, junk);
            } else {
                s.replace_range(at..at + 1, junk.encode_utf8(&mut [0; 4]));
            }
        }
    }

    /// One input, its class drawn by weight. The classes that need big
    /// integers to build (`halfway`) or run to hundreds of digits are the
    /// expensive ones and get the smaller shares.
    fn random_input(r: &mut Rng, s: &mut String) {
        s.clear();
        match r.below(100) {
            0..=14 => short_decimal(r, s),
            15..=17 => short_tie(r, s),
            18..=39 => long_mantissa(r, s),
            40..=61 => round_trip(r, s),
            62..=67 => halfway(r, s),
            68..=77 => boundary(r, s),
            78..=81 => long_digits(r, s),
            82..=91 => zeros(r, s),
            _ => malformed(r, s),
        }
    }

    fn random_inputs(seed: u64, count: u64) {
        let mut r = Rng(seed);
        let mut s = String::new();
        for i in 0..count {
            random_input(&mut r, &mut s);
            let (ours, core) = (ours(&s), cores(&s));
            if ours != core {
                let shown: String = s.chars().take(200).collect();
                panic!(
                    "seed {seed:#x}, input {i}: {shown:?} ({} bytes): {ours:x?} against {core:x?}",
                    s.len()
                );
            }
        }
    }

    /// `exact` by itself on an unsigned number inside the table's range, the
    /// only inputs `number` hands it; `None` for anything else.
    fn exact_alone(s: &str) -> Option<u64> {
        let (mantissa, exp) = match s.split_once(['e', 'E']) {
            Some((mantissa, exp)) => (mantissa, exp.parse::<i64>().ok()?),
            None => (s, 0),
        };
        if !mantissa.bytes().all(|c| c.is_ascii_digit() || c == b'.') {
            return None;
        }
        let digits = mantissa.bytes().filter(|&c| c != b'.');
        let significant = digits.skip_while(|&c| c == b'0').count() as i64;
        let frac_len = mantissa.split_once('.').map_or(0, |(_, frac)| frac.len());
        let exp10 = exp - frac_len as i64;
        let q = exp10 + (significant - 19).max(0);
        (significant > 0 && (MIN_Q..=MAX_Q).contains(&q)).then(|| exact(mantissa.as_bytes(), exp10))
    }

    /// The exact path on its own, fed what the faster paths normally settle.
    /// In `parse_f64` it only sees the inputs whose two brackets disagree,
    /// and Eisel-Lemire's "cannot decide" return, its other way in, has no
    /// short input known to produce it; so here every kind of number goes
    /// through the division, the overflow to infinity included.
    #[test]
    fn exact_path_alone_agrees_with_core() {
        let count = if cfg!(debug_assertions) {
            30_000
        } else {
            600_000
        };
        let mut r = Rng(0xA076_1D64_78BD_642F);
        let mut s = String::new();
        let mut checked = 0;
        for i in 0..count {
            s.clear();
            match r.below(13) {
                0 | 1 => short_decimal(&mut r, &mut s),
                2..=4 => long_mantissa(&mut r, &mut s),
                5 | 6 => round_trip(&mut r, &mut s),
                7 => halfway(&mut r, &mut s),
                8 | 9 => boundary(&mut r, &mut s),
                10 => long_digits(&mut r, &mut s),
                11 => short_tie(&mut r, &mut s),
                _ => zeros(&mut r, &mut s),
            }
            let unsigned = s.trim_start_matches(['+', '-']);
            let (Some(core), Some(ours)) = (cores(unsigned), exact_alone(unsigned)) else {
                continue;
            };
            let shown: String = unsigned.chars().take(200).collect();
            assert_eq!(
                ours,
                core,
                "input {i}: {shown:?} ({} bytes)",
                unsigned.len()
            );
            checked += 1;
        }
        assert!(
            checked > count / 2,
            "only {checked} of {count} inputs reached the exact path"
        );
        eprintln!("exact_path_alone_agrees_with_core: {checked} inputs");
    }

    /// Every mantissa of one to four digits at every exponent, from where
    /// everything is zero to where everything is infinite: 6,559,344 inputs.
    #[test]
    fn every_short_mantissa_agrees_with_core() {
        let mut s = String::new();
        let mut count = 0u64;
        for mantissa in 1..=9999u32 {
            for exp in -345..=310 {
                s.clear();
                write!(s, "{mantissa}e{exp}").unwrap();
                check(&s);
                count += 1;
            }
        }
        eprintln!("every_short_mantissa_agrees_with_core: {count} inputs");
    }

    /// Five million random inputs across the classes above. A debug build,
    /// which is what `cargo test` runs by default, takes the first two million
    /// of the same sequence to stay within seconds.
    #[test]
    fn random_inputs_agree_with_core() {
        let count = if cfg!(debug_assertions) {
            2_000_000
        } else {
            5_000_000
        };
        random_inputs(0x9E37_79B9_7F4A_7C15, count);
        eprintln!("random_inputs_agree_with_core: {count} inputs");
    }

    /// Two hundred million random inputs, split over the machine's cores.
    /// `cargo test --release -p zipp-vm --lib num_parse -- --ignored`
    #[test]
    #[ignore = "200 million inputs; run in release"]
    fn random_inputs_agree_with_core_200m() {
        const TOTAL: u64 = 200_000_000;
        let threads = std::thread::available_parallelism()
            .map_or(1, |n| n.get() as u64)
            .min(16);
        std::thread::scope(|scope| {
            for t in 0..threads {
                scope.spawn(move || {
                    random_inputs(
                        0xD1B5_4A32_D192_ED03 ^ (t + 1) << 32,
                        TOTAL.div_ceil(threads),
                    );
                });
            }
        });
        let count = TOTAL.div_ceil(threads) * threads;
        eprintln!("random_inputs_agree_with_core_200m: {count} inputs on {threads} threads");
    }
