#[test]
fn compiled_training_v2_matches_pytorch_activations_losses_and_optimizers() {
    // Golden values generated by CPU PyTorch 2.11 (`py -3.11`): for four
    // sequential steps, the loss, every gradient, every weight and the
    // optimizer's state buffers (momentum buffer, Adam moments and step),
    // by running the fixture eagerly with `case` set to each name. Measured
    // deviations are ulp-level (max 2.4e-7 on losses, 1.2e-7 on weights).
    let fixture = include_str!("fixtures/torch_training_v2.py");
    let expected = include_str!("fixtures/torch_training_v2_expected.json");
    for case in TRAINING_V2_CASES {
        let source = format!(
            "case = {case:?}\n{fixture}\nexpected = {expected}\nexpected = expected[case]\n{}",
            r#"
compiled = torch.compile(train_step, training=True)
index = 0
def done(loss):
    global index
    actual = state(loss)
    assert len(actual) == len(expected[index]), (len(actual), len(expected[index]))
    worst = max(abs(a - b) for a, b in zip(actual, expected[index]))
    assert worst < 2e-6, "step %d deviates by %g" % (index, worst)
    index += 1
for step in range(len(expected)):
    compiled(inputs, classes).submit(done)
print(case, 'parity', index)
"#
        );
        assert_eq!(run(&source).unwrap(), [format!("{case} parity 4")], "{case}");
    }
}

#[test]
fn compiled_optimizer_state_continues_into_eager_steps() {
    // Two compiled steps write the momentum buffer / Adam moments and step
    // count into `optimizer.state` under the eager keys, so two eager steps
    // continue the same PyTorch trajectory.
    let fixture = include_str!("fixtures/torch_training_v2.py");
    let expected = include_str!("fixtures/torch_training_v2_expected.json");
    for case in ["sigmoid_ce_momentum", "tanh_softce_adamw"] {
        let source = format!(
            "case = {case:?}\n{fixture}\nexpected = {expected}\nexpected = expected[case]\n{}",
            r#"
compiled = torch.compile(train_step, training=True)
seen = []
def check(loss):
    actual = state(loss)
    worst = max(abs(a - b) for a, b in zip(actual, expected[len(seen)]))
    assert len(actual) == len(expected[len(seen)]) and worst < 1e-5, worst
    seen.append(1)
for step in range(2):
    compiled(inputs, classes).submit(check)
for step in range(2):
    check(train_step(inputs, classes))
print(case, len(seen), sorted(set(str(entry.get("step")) for entry in optimizer.state.values())))
"#
        );
        let steps = if case.ends_with("adamw") { "['4']" } else { "['None']" };
        assert_eq!(run(&source).unwrap(), [format!("{case} 4 {steps}")], "{case}");
    }
}

