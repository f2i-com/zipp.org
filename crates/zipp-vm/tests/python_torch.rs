#[test]
fn compiled_inference_records_graphs_and_preserves_cpu_torch() {
    let output = run(r#"
import torch
import torch.nn as nn
model = nn.Sequential(nn.Linear(2, 3), nn.ReLU(), nn.Linear(3, 1))
with torch.no_grad():
    for parameter in model.parameters():
        parameter.fill_(0.5)
x = torch.tensor([[1.0, 2.0], [3.0, 4.0]])
expected = model(x).tolist()
pending = torch.compile(model)(x)
print(pending.shape)
def done(value):
    print(value.tolist() == expected, pending.backend)
pending.submit(done)
@torch.compile
def square_sum(a):
    return (a * a + 1.0).sum()
square_sum(x).submit(lambda value: print(value.item()))
for action in [lambda: torch.tensor([1.0], device='cuda'), lambda: x.to('gpu'), lambda: model.to('cuda'), lambda: torch.device('cuda')]:
    try:
        action()
    except RuntimeError:
        print('unsupported device rejected')
try:
    pending.backward()
except NotImplementedError:
    print('inference only')
"#).unwrap();
    assert_eq!(output[0], "torch.Size([2, 1])");
    assert!(output[1].starts_with("True "));
    assert_eq!(output[2], "34.0");
    assert_eq!(&output[3..7], ["unsupported device rejected"; 4]);
    assert_eq!(output[7], "inference only");
}

#[test]
fn compiled_training_accumulates_shared_and_input_gradients() {
    let out = run(r#"
import torch
from torch import nn
x = torch.tensor([[1.0, -2.0], [0.0, 3.0]], requires_grad=True)
w = nn.Parameter(torch.tensor([[0.5, -0.25], [0.75, 0.25]]))
b = nn.Parameter(torch.tensor(0.125))
optimizer = torch.optim.SGD([{'params': [w], 'lr': 0.01}, {'params': [b], 'lr': 0.02}], maximize=True)
def step(x):
    optimizer.zero_grad()
    a = x @ w
    # Shared weight, shared branch, scalar broadcasting, transpose, square,
    # reductions and scalar division all contribute to the same leaves.
    loss = ((a + (x @ w) - b) ** 2).sum() / 4.0 + a.T.mean()
    loss.backward()
    optimizer.step()
    return loss
original_w = w.detach().clone()
original_b = b.detach().clone()
expected = []
for i in range(2):
    loss = step(x)
    expected.append([loss.item(), w.detach().clone(), b.detach().clone(), w.grad.clone(), b.grad.clone(), x.grad.clone()])
w.data = original_w
b.data = original_b
x.grad = None
compiled = torch.compile(step, training=True)
index = 0
def done(loss):
    global index
    e = expected[index]
    assert abs(loss.item() - e[0]) < 1e-5
    for actual, wanted in zip([w, b, w.grad, b.grad, x.grad], e[1:]):
        assert torch.allclose(actual, wanted, atol=1e-5), str(actual.tolist())
    index += 1
for i in range(2):
    compiled(x).submit(done)
print('shared and input gradients', index)
"#).unwrap();
    assert_eq!(out, ["shared and input gradients 2"]);
}

