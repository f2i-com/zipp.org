#[test]
fn compiled_training_rejects_what_the_graph_cannot_express() {
    let out = run(r#"
import torch
from torch import nn
import torch.nn.functional as F
x = torch.tensor([[1.0, 2.0], [3.0, 4.0]])
targets = torch.tensor([0, 1])
model = nn.Linear(2, 3)
def attempt(name, loss_fn, optimizer=None):
    optimizer = optimizer or torch.optim.SGD(model.parameters(), lr=0.1)
    def step(x, targets):
        optimizer.zero_grad()
        loss = loss_fn(model(x), targets)
        loss.backward()
        optimizer.step()
        return loss
    try:
        torch.compile(step, training=True)(x, targets)
        print(name, 'accepted')
    except (NotImplementedError, TypeError, ValueError) as error:
        print(name, '->', error)
attempt('amsgrad', F.cross_entropy, torch.optim.Adam(model.parameters(), amsgrad=True))
attempt('rmsprop', F.cross_entropy, torch.optim.RMSprop(model.parameters()))
attempt('softmax dim 0', lambda o, t: F.softmax(o, dim=0).sum())
attempt('nll_loss', lambda o, t: F.nll_loss(F.log_softmax(o, -1), t))
attempt('label smoothing', lambda o, t: F.cross_entropy(o, t, label_smoothing=0.1))
attempt('reduction none', lambda o, t: F.cross_entropy(o, t, reduction='none').sum())
attempt('targets rank 2', lambda o, t: F.cross_entropy(o, t.reshape(2, 1)))
attempt('targets out of range', lambda o, t: F.cross_entropy(o, torch.tensor([0, 7])))
attempt('two dims', lambda o, t: (o * o).sum((0, 1)))
attempt('float64', lambda o, t: o.sum(dtype=torch.float64))
attempt('integer arithmetic', lambda o, t: (o + t.reshape(2, 1)).sum())
attempt('gelu tanh form', lambda o, t: F.gelu(o, approximate='tanh').sum())
attempt('sum reduction', lambda o, t: F.cross_entropy(o, t, reduction='sum'))
attempt('soft targets', lambda o, t: F.cross_entropy(o, torch.tensor([[0.2, 0.3, 0.5], [1.0, 0.0, 0.0]])))
"#)
    .unwrap();
    assert_eq!(
        out,
        [
            "amsgrad -> GPU Adam does not support amsgrad",
            "rmsprop -> Compiled GPU training supports SGD, Adam and AdamW; RMSprop is not captured",
            "softmax dim 0 -> GPU softmax supports the last dimension of a tensor with at least one dimension",
            "nll_loss -> GPU nll_loss is not captured; use F.cross_entropy on the logits with integer class targets",
            "label smoothing -> GPU cross_entropy supports no class weights or label smoothing",
            "reduction none -> GPU cross_entropy supports reduction='mean' or 'sum'",
            "targets rank 2 -> GPU cross_entropy supports class targets of shape [N] for logits [N, C]",
            "targets out of range -> cross_entropy targets must be a tensor of integer class indices in [0, C)",
            "two dims -> GPU sum reduces all elements or one dimension",
            "float64 -> GPU sum computes float32 only",
            "integer arithmetic -> GPU compilation requires float32 tensors; integer tensors are accepted only as cross_entropy class targets",
            "gelu tanh form accepted",
            "sum reduction accepted",
            "soft targets accepted",
        ]
    );
}

#[test]
fn compiled_training_rejects_optimizer_state_changes_since_capture() {
    let out = run(r#"
import torch
from torch import nn
import torch.nn.functional as F
model = nn.Linear(2, 1)
x = torch.tensor([[1.0, 2.0], [3.0, 4.0]])
y = torch.tensor([[1.0], [0.0]])
def make(optimizer):
    def step(x, y):
        optimizer.zero_grad()
        loss = F.mse_loss(model(x), y)
        loss.backward()
        optimizer.step()
        return loss
    return torch.compile(step, training=True), step
report = lambda error: print(str(error))
before = model.weight.detach().clone()
sgd = torch.optim.SGD(model.parameters(), lr=0.1, momentum=0.9)
compiled, eager = make(sgd)
compiled(x, y).submit(lambda loss: print(sorted(sgd.state[id(model.weight)])))
pending = compiled(x, y)
sgd.state[id(model.weight)]['momentum_buffer'] = torch.zeros(1, 2)
pending.submit(lambda loss: print('unexpected'), report)
pending = compiled(x, y)
sgd.state.clear()
pending.submit(lambda loss: print('unexpected'), report)
adam = torch.optim.Adam(model.parameters())
compiled, eager = make(adam)
compiled(x, y).submit(lambda loss: print(adam.state[id(model.weight)]['step']))
pending = compiled(x, y)
eager(x, y)
pending.submit(lambda loss: print('unexpected'), report)
print(adam.state[id(model.weight)]['step'], torch.equal(model.weight, before))
"#)
    .unwrap();
    assert_eq!(
        out,
        [
            "['momentum_buffer']",
            "GPU training result is stale; optimizer state changed before completion",
            "GPU training result is stale; optimizer state changed before completion",
            "1",
            "GPU training result is stale; optimizer changed before completion",
            "2 False",
        ]
    );
}
