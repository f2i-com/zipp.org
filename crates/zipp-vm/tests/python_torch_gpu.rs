//! `torch.compile` beyond dense layers: eager operations on parameters inside
//! a compiled training step, views, permutations, division, square roots,
//! multi-dimensional reductions and vectors, compared with PyTorch, with
//! eager Zipp and between per-call and prepared execution; and the cases the
//! graph cannot express, which must raise instead of training silently wrong.
#![cfg(feature = "python")]
use zipp_vm::frontend::compile_python_program;

fn run(source: &str) -> Result<Vec<String>, String> {
    let source = source.to_owned();
    std::thread::Builder::new()
        .stack_size(256 << 20)
        .spawn(move || {
            let modules = vec![("main".to_owned(), source)];
            let mut compiled = compile_python_program("main", &modules, &[], &[], false)?;
            let state = compiled.state_mut();
            state.set_limits(400_000_000, None);
            state.run_init()?;
            Ok(state.take_output())
        })
        .expect("spawn")
        .join()
        .expect("test thread")
}

